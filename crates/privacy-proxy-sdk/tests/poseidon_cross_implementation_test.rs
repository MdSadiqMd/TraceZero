#[test]
fn test_poseidon_5_inputs_binding_hash() {
    // Test: Poseidon(DOMAIN_BIND, nullifierHash, recipient, relayer, fee)
    // This is used for withdrawal binding hash
    
    let nullifier_hash = [
        0x0c, 0x8e, 0x3d, 0x8f, 0x5a, 0x7c, 0x9b, 0x2e,
        0x1f, 0x4d, 0x6a, 0x8c, 0x3b, 0x5e, 0x7f, 0x9a,
        0x2d, 0x4c, 0x6b, 0x8a, 0x1e, 0x3f, 0x5d, 0x7c,
        0x9b, 0x2a, 0x4d, 0x6e, 0x8f, 0x1a, 0x3c, 0x5e,
    ];
    
    let recipient = [
        0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x48,
        0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x50,
        0x51, 0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58,
        0x59, 0x5a, 0x5b, 0x5c, 0x5d, 0x5e, 0x5f, 0x60,
    ];
    
    let relayer = [
        0x61, 0x62, 0x63, 0x64, 0x65, 0x66, 0x67, 0x68,
        0x69, 0x6a, 0x6b, 0x6c, 0x6d, 0x6e, 0x6f, 0x70,
        0x71, 0x72, 0x73, 0x74, 0x75, 0x76, 0x77, 0x78,
        0x79, 0x7a, 0x7b, 0x7c, 0x7d, 0x7e, 0x7f, 0x80,
    ];
    
    let fee = 10_000_000u64; // 0.01 SOL
    
    // Manually construct the binding hash using poseidon_hash
    let domain_bytes = DOMAIN_BIND.to_be_bytes();
    let mut domain_32 = [0u8; 32];
    domain_32[24..].copy_from_slice(&domain_bytes);
    
    let fee_bytes = fee.to_be_bytes();
    let mut fee_32 = [0u8; 32];
    fee_32[24..].copy_from_slice(&fee_bytes);
    
    let result = poseidon_hash(&[
        &domain_32,
        &nullifier_hash,
        &recipient,
        &relayer,
        &fee_32,
    ]).unwrap();
    
    println!("Binding hash result: {:02x?}", result);
    
    // Verify deterministic
    let result2 = poseidon_hash(&[
        &domain_32,
        &nullifier_hash,
        &recipient,
        &relayer,
        &fee_32,
    ]).unwrap();
    assert_eq!(result, result2, "Binding hash must be deterministic");
}

#[test]
fn test_poseidon_merkle_tree_nodes() {
    // Test: Poseidon(left, right)
    // This is used for Merkle tree node hashing
    
    let left = [
        0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
        0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10,
        0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18,
        0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f, 0x20,
    ];
    
    let right = [
        0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28,
        0x29, 0x2a, 0x2b, 0x2c, 0x2d, 0x2e, 0x2f, 0x30,
        0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38,
        0x39, 0x3a, 0x3b, 0x3c, 0x3d, 0x3e, 0x3f, 0x40,
    ];
    
    let result = poseidon_hash(&[&left, &right]).unwrap();
    
    // Expected output from circomlibjs
    let expected_merkle_hash = [
        0x05, 0xd4, 0xf0, 0x98, 0x83, 0xf7, 0x4d, 0x30,
        0xcd, 0x8b, 0x4a, 0xf3, 0xe5, 0xe0, 0x11, 0x30,
        0xa4, 0x7d, 0x7b, 0xb5, 0x72, 0xc6, 0x6f, 0x46,
        0x1e, 0xf5, 0x34, 0x89, 0x89, 0x53, 0x0e, 0xe7,
    ];
    
    assert_eq!(
        result, expected_merkle_hash,
        "Merkle node hash must match circomlibjs output"
    );
    
    // Verify order matters (not commutative)
    let result_reversed = poseidon_hash(&[&right, &left]).unwrap();
    assert_ne!(result, result_reversed, "Poseidon must not be commutative");
}

