#[test]
fn test_zero_inputs() {
    // Test edge case: all zeros
    // Note: SDK validates non-zero values, so this test verifies the validation works
    let zero = [0u8; 32];
    
    // Nullifier hash with zero should fail validation
    let result = generate_nullifier_hash(&zero);
    assert!(result.is_err(), "Zero nullifier should be rejected");
    
    // Commitment with zero nullifier should fail
    let commitment = generate_commitment(&zero, &zero, 0);
    assert!(commitment.is_err(), "Zero nullifier in commitment should be rejected");
    
    // But we can test with non-zero nullifier and zero secret
    let non_zero_nullifier = [
        0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ];
    
    let result = generate_nullifier_hash(&non_zero_nullifier).unwrap();
    
    // Should be deterministic
    let result2 = generate_nullifier_hash(&non_zero_nullifier).unwrap();
    assert_eq!(result, result2, "Hash must be deterministic");
}

